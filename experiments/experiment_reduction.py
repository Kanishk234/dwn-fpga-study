"""EXPERIMENT: how much of dwn_core is the reduction, really?

`docs/jsc/phase2-ledger.md` carries this as an open question, and `dse/area_model.py` depends on the
answer. The current number is an INFERENCE, not a measurement:

    dwn_core measured 108 LUTs for 50 nodes + 5 x popcount(10) + argmax(5)
    one DWN node == one LUT6 (brief §4), so nodes ~= 50
    therefore reduction ~= 58 LUTs, ~54% of the core

That subtraction is only sound if a node really costs exactly one LUT6 and nothing is shared
across the boundary. Vivado inlined `lut_node`, `popcount` and `argmax` into the top level, so
the hierarchical report attributes all 108 LUTs to `dwn_core` and cannot separate them.

Why it matters beyond tidiness: `docs/jsc/dse-plan.md` §3 deferred Learnable Reduction on exactly
this number -- *"if it's 40% of area, building the pyramid is obviously worth it; if it's 3%,
this was never an interesting axis."* 54% clears that bar comfortably, but not if it is wrong.

So synthesize both halves separately and see whether they add up:

    nodes_only       50 lut_node instances, real tables, real wiring
    reduction_only   5 x popcount(10) + argmax(5, 4-bit)

DELIBERATELY OUTSIDE THE MAIN FLOW: writes to build/experiments/, touches no shipped RTL.

A caveat that applies to both numbers: out-of-context synthesis of a fragment cannot share logic
with its neighbours, so each part measured alone is an UPPER bound on its cost in context. If
the two sum to more than 108, that difference is cross-boundary optimization, not an error.

Usage:
    python scripts/experiment_reduction.py training/artifacts/<run>_checkpoint.pt
"""

import argparse
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'exporter'))
sys.path.insert(0, os.path.join(REPO, 'rtlgen'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))

from extract import load_checkpoint, layer_indices, extract_tables, extract_wiring  # noqa: E402
from emit_core import table_to_hex  # noqa: E402
from run_gate1 import find_vivado_bin  # noqa: E402
from run_synth import DEFAULT_PART, parse_utilization, parse_wns, run_one  # noqa: E402

MEASURED_CORE = 108      # dwn_core, out-of-context, xc7a35tcpg236-1 (Phase 1)


def emit_nodes_only(ck, path):
    """The LUT layer alone: real tables and real wiring, no popcount, no argmax."""
    cfg = ck['config']
    n = cfg['n']
    sd = ck['state_dict']
    first = layer_indices(sd)[0]
    tables = extract_tables(sd, first)
    wiring, _ = extract_wiring(sd, first, n)
    count = tables.shape[0]
    input_bits = 16 * cfg['thermometer_bits']

    L = ['// EXPERIMENT -- generated by scripts/experiment_reduction.py',
         '// The LUT layer with NO reduction. Not part of the shipped design.',
         '',
         '`timescale 1ns / 1ps',
         '`default_nettype none',
         '',
         'module nodes_only (',
         f'    input  wire [{input_bits-1}:0] x,',
         f'    output wire [{count-1}:0] layer',
         ');',
         '']
    for j in range(count):
        # Same MSB-first reversal the real emitter uses; the address bit order changes which
        # table entry is read, so a "simplified" wiring here would measure a different circuit.
        slots = ', '.join(f'x[{b}]' for b in reversed(wiring[j].tolist()))
        L.append(f"    lut_node #(.N({n}), .TABLE(64'h{table_to_hex(tables[j]):016X}))")
        L.append(f'        u_n{j} (.addr({{{slots}}}), .out(layer[{j}]));')
    L += ['', 'endmodule', '', '`default_nettype wire']

    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write('\n'.join(L) + '\n')
    return count, input_bits


def emit_reduction_only(ck, path, final_width):
    """The reduction alone: per-class popcounts plus the argmax tree."""
    num_classes = ck['config']['num_classes']
    group = final_width // num_classes
    score_w = int(np.ceil(np.log2(group + 1)))
    idx_w = max(1, int(np.ceil(np.log2(num_classes))))

    L = ['// EXPERIMENT -- generated by scripts/experiment_reduction.py',
         '// popcount + argmax with NO LUT layer. Not part of the shipped design.',
         '',
         '`timescale 1ns / 1ps',
         '`default_nettype none',
         '',
         'module reduction_only (',
         f'    input  wire [{final_width-1}:0] layer,',
         f'    output wire [{idx_w-1}:0] class_idx',
         ');',
         '',
         f'    wire [{num_classes*score_w-1}:0] scores;']
    for c in range(num_classes):
        lo, hi = c * group, (c + 1) * group - 1
        L.append(f'    popcount #(.WIDTH({group})) u_pc{c} '
                 f'(.bits(layer[{hi}:{lo}]), .count(scores[{c*score_w+score_w-1}:{c*score_w}]));')
    L += ['',
          f'    argmax #(.K({num_classes}), .W({score_w})) u_argmax '
          f'(.scores_flat(scores), .index(class_idx));',
          '', 'endmodule', '', '`default_nettype wire']

    open(path, 'w').write('\n'.join(L) + '\n')
    return group, score_w


def main():
    ap = argparse.ArgumentParser(description='Measure the reduction vs the LUT layer.')
    ap.add_argument('checkpoint')
    ap.add_argument('--part', default=DEFAULT_PART)
    ap.add_argument('--vivado-bin', default=None)
    args = ap.parse_args()

    ck = load_checkpoint(args.checkpoint)
    work = os.path.join(REPO, 'build', 'experiments', 'reduction')
    os.makedirs(work, exist_ok=True)

    nodes_v = os.path.join(work, 'nodes_only.v')
    red_v = os.path.join(work, 'reduction_only.v')
    count, input_bits = emit_nodes_only(ck, nodes_v)
    group, score_w = emit_reduction_only(ck, red_v, count)

    print(f'nodes_only     : {count} lut_node, {input_bits}-bit input')
    print(f'reduction_only : {ck["config"]["num_classes"]} x popcount({group}) '
          f'-> {score_w}-bit scores -> argmax')
    print()

    vivado_bin = find_vivado_bin(args.vivado_bin)
    prim = ['rtl/lut_node.v', 'rtl/popcount.v', 'rtl/argmax.v']
    rel = os.path.relpath(work, REPO).replace('\\', '/')

    results = {}
    for top, srcs in (('nodes_only', ['rtl/lut_node.v', f'{rel}/nodes_only.v']),
                      ('reduction_only', ['rtl/popcount.v', 'rtl/argmax.v',
                                          f'{rel}/reduction_only.v'])):
        print(f'=== synthesizing {top} (out-of-context) ===')
        ok, out_dir = run_one(vivado_bin, top, srcs, args.part,
                              os.path.join(REPO, 'build', 'experiments'))
        if not ok:
            return 1
        util = parse_utilization(os.path.join(out_dir, 'utilization.rpt'))
        results[top] = (util.get('luts'), parse_wns(os.path.join(out_dir, 'timing_summary.rpt')))

    nodes_luts = results['nodes_only'][0]
    red_luts = results['reduction_only'][0]
    total = (nodes_luts or 0) + (red_luts or 0)

    print()
    print('=' * 68)
    print(f'{"part":18s} {"LUTs":>6} {"% of measured core":>20}')
    print('-' * 68)
    print(f'{"nodes_only":18s} {nodes_luts:>6} {100*nodes_luts/MEASURED_CORE:>19.1f}%')
    print(f'{"reduction_only":18s} {red_luts:>6} {100*red_luts/MEASURED_CORE:>19.1f}%')
    print('-' * 68)
    print(f'{"sum":18s} {total:>6} {100*total/MEASURED_CORE:>19.1f}%')
    print(f'{"dwn_core measured":18s} {MEASURED_CORE:>6} {"(Phase 1)":>20}')
    print('=' * 68)
    print()
    print(f'inferred-by-subtraction estimate was {MEASURED_CORE - count} LUTs '
          f'({100*(MEASURED_CORE-count)/MEASURED_CORE:.0f}% of the core)')
    print(f'measured reduction                   {red_luts} LUTs '
          f'({100*red_luts/MEASURED_CORE:.0f}% of the core)')
    print()
    # dse-plan §3 set the decision bar explicitly, so state the verdict against it.
    pct = 100 * red_luts / MEASURED_CORE
    if pct >= 40:
        print(f'VERDICT: {pct:.0f}% >= 40% -- dse-plan sec.3 says building Learnable Reduction is')
        print('"obviously worth it". It remains unimplemented upstream, so it is our code to')
        print('write, and it is a real Group A axis rather than a deferred one.')
    elif pct <= 10:
        print(f'VERDICT: {pct:.0f}% <= 10% -- dse-plan sec.3 says "this was never an interesting')
        print('axis". Drop Learnable Reduction and say so in the writeup.')
    else:
        print(f'VERDICT: {pct:.0f}% is between the 3% and 40% bars dse-plan sec.3 set. Judgement')
        print('call, not a rule -- weigh it against the encoder, which is far larger.')
    print()
    print('CAVEAT: each fragment synthesized alone cannot share logic with its neighbours, so')
    print('both figures are UPPER bounds on the in-context cost. A sum above 108 is')
    print('cross-boundary optimization in the real core, not an error here.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
