"""EXPERIMENT: does per-feature comparator narrowing actually save the LUTs the model predicts?

analyze_encoder.py estimates 1519 -> 1330 LUTs (12%) by assuming comparator cost is linear in
width. That assumption is worth exactly nothing until it is measured -- carry-chain comparators
come in granularity of 4 bits, and a 15-bit compare may well cost the same as a 16-bit one.

So this emits a narrowed encoder into build/, synthesizes it out-of-context, and reports the
real number against the 1519 the shipped encoder measures.

DELIBERATELY OUTSIDE THE MAIN FLOW. Nothing here touches build/rtl or the shipped emitter.
Narrowing is a SPEC change -- the golden model would have to narrow identically for Gate 1 to
stay bit-exact -- so it does not get adopted on the strength of an estimate.

The narrowing itself is exact against the Q3.12 spec: dropping the low s bits of a signed value
is an arithmetic shift, which is floor division, which is the same floor the encoding already
uses. Comparing floor(x*2^(12-s)) against floor(t*2^(12-s)) is therefore identical to the
current comparison whenever s is small enough that no sample and threshold collide in a bucket
-- which is precisely the per-feature minimum analyze_encoder.py computes.

Usage:
    python exporter/experiment_narrow_encoder.py training/artifacts/<run>_checkpoint.pt
"""

import argparse
import os
import sys

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, 'exporter'))
sys.path.insert(0, os.path.join(REPO, 'scripts'))
from extract import (load_checkpoint, layer_indices,  # noqa: E402
                     extract_wiring)

sys.path.insert(0, REPO)
import datasets  # noqa: E402

# These are JSC ANALYSES, not part of the shipped flow -- `experiments/` is deliberately
# outside the dataset-agnostic contract in datasets/__init__.py (which covers exporter/,
# rtlgen/, rtl/, tb/, scripts/ and harness/). Several bake in JSC measurements outright,
# e.g. LUT_PER_BIT = 1519 / 202. So the JSC binding is stated HERE, explicitly, rather
# than inherited from a module constant that pretended to be universal.
FRAC_BITS = datasets.JSC.frac_bits
WORD_BITS = datasets.JSC.word_bits
from analyze_encoder import min_frac_bits  # noqa: E402
from run_gate1 import find_vivado_bin  # noqa: E402
from run_synth import run_one, parse_utilization, parse_wns, DEFAULT_PART  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('checkpoint')
    ap.add_argument('--vectors')
    ap.add_argument('--part', default=DEFAULT_PART)
    args = ap.parse_args()

    ck = load_checkpoint(args.checkpoint)
    cfg = ck['config']
    n, z = cfg['n'], cfg['thermometer_bits']
    thresholds = ck['thermometer']['thresholds'].numpy()

    wiring, _ = extract_wiring(ck['state_dict'], layer_indices(ck['state_dict'])[0], n)
    used = np.unique(wiring)

    vec_path = args.vectors or args.checkpoint.replace('_checkpoint.pt', '_testvectors.npz')
    x_raw = np.load(vec_path)['x_raw'].astype(np.float64)

    # Per-feature minimum fractional bits, and the resulting shift.
    frac_of = {}
    for f in range(thresholds.shape[0]):
        sel = used[(used // z) == f]
        if sel.size:
            frac_of[f] = min_frac_bits(x_raw[:, f], thresholds[f, sel % z].astype(np.float64))

    # Verify in numpy before generating any RTL: the narrowed encoding must reproduce the
    # Q3.12 encoding bit for bit on every available sample.
    mism = 0
    for b in used.tolist():
        f, t_idx = divmod(int(b), z)
        s = FRAC_BITS - frac_of[f]
        ref = np.floor(x_raw[:, f] * 2**FRAC_BITS) > np.floor(thresholds[f, t_idx] * 2**FRAC_BITS)
        got = (np.floor(x_raw[:, f] * 2**FRAC_BITS).astype(np.int64) >> s) > \
              (int(np.floor(thresholds[f, t_idx] * 2**FRAC_BITS)) >> s)
        mism += int((ref != got).sum())
    print(f'numpy check: {mism} bit differences vs the Q3.12 encoding across '
          f'{used.size} comparators x {x_raw.shape[0]} samples')
    if mism:
        print('ABORT: narrowing is not bit-exact -- do not synthesize this.')
        return 1

    # ---- emit the narrowed encoder ----
    work = os.path.join(REPO, 'build', 'experiments', 'narrow_encoder')
    os.makedirs(work, exist_ok=True)
    total_bits = thresholds.size

    L = ['// EXPERIMENT -- generated by exporter/experiment_narrow_encoder.py.',
         '// Per-feature comparator widths. Not part of the shipped design.',
         '',
         '`timescale 1ns / 1ps',
         '`default_nettype none',
         '',
         'module thermometer_encoder_narrow (',
         f'    input  wire [{thresholds.shape[0]*WORD_BITS-1}:0] x_flat,',
         f'    output reg  [{total_bits-1}:0] bits',
         ');',
         '',
         '    always @* begin',
         f'        bits = {total_bits}\'b0;']

    widths = {}
    for b in sorted(used.tolist()):
        f, t_idx = divmod(int(b), z)
        s = FRAC_BITS - frac_of[f]
        w = WORD_BITS - s
        widths[f] = w
        t = int(np.floor(thresholds[f, t_idx] * 2**FRAC_BITS)) >> s
        # Slicing off the low s bits of a signed word IS the arithmetic shift; the sign bit
        # stays in place because the slice keeps the top of the word.
        lhs = f'$signed(x_flat[{f}*{WORD_BITS}+{s} +: {w}])'
        rhs = f'$signed({w}\'sd{t})' if t >= 0 else f'-$signed({w}\'sd{-t})'
        L.append(f'        bits[{b:4d}] = {lhs} > {rhs};')

    L += ['    end', '', 'endmodule', '', '`default_nettype wire']
    path = os.path.join(work, 'thermometer_encoder_narrow.v')
    with open(path, 'w') as fh:
        fh.write('\n'.join(L) + '\n')

    print(f'wrote {os.path.relpath(path, REPO)}')
    print('  per-feature widths: ' +
          ', '.join(f'f{f}={w}' for f, w in sorted(widths.items())))
    print()

    # ---- synthesize and compare ----
    vivado_bin = find_vivado_bin(None)
    rel = os.path.relpath(path, REPO).replace('\\', '/')
    print('=== synthesizing thermometer_encoder_narrow (out-of-context) ===')
    ok, out_dir = run_one(vivado_bin, 'thermometer_encoder_narrow', [rel],
                          args.part, os.path.join(REPO, 'build', 'experiments'))
    if not ok:
        return 1

    util = parse_utilization(os.path.join(out_dir, 'utilization.rpt'))
    wns = parse_wns(os.path.join(out_dir, 'timing_summary.rpt'))
    luts = util.get('luts')

    print()
    print('=' * 60)
    print(f'{"variant":32s} {"LUTs":>7} {"vs baseline":>13}')
    print('-' * 60)
    print(f'{"thermometer_encoder (shipped, 16b)":32s} {1519:>7} {"--":>13}')
    print(f'{"thermometer_encoder_narrow":32s} {luts:>7} '
          f'{100*(luts-1519)/1519:>+12.1f}%')
    print('=' * 60)
    print(f'predicted by the linear model: 1330 LUTs (-12.4%)')
    if wns is not None:
        print(f'narrow variant WNS: {wns:+.3f} ns')
    return 0


if __name__ == '__main__':
    sys.exit(main())
